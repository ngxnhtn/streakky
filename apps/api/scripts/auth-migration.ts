/**
 * Writes the SQL that better-auth's tables still need as the next D1 migration, so they live with
 * our own migrations and deploy applies them. Run it from apps/api after changing the auth options
 * or upgrading better-auth:
 *
 *   vpx scripts/auth-migration.ts
 *
 * It applies every existing migration to an empty SQLite database, asks better-auth what is
 * missing from it with the Worker's own options, and writes that as `migrations/NNNN_auth.sql`.
 * When nothing is missing it writes nothing.
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { DatabaseSync } from "node:sqlite";
import { fileURLToPath } from "node:url";
import { getMigrations } from "better-auth/db/migration";
import { authOptions } from "../src/auth.ts";

const migrationsDir = fileURLToPath(new URL("../migrations", import.meta.url));

const files = (await readdir(migrationsDir)).filter((name) => name.endsWith(".sql")).sort();
const database = new DatabaseSync(":memory:");
for (const name of files) database.exec(await readFile(join(migrationsDir, name), "utf8"));

const { toBeCreated, toBeAdded, compileMigrations } = await getMigrations(
  authOptions({
    database,
    // the schema doesn't depend on these
    secret: "schema-only-secret-schema-only-secret",
    allowlist: "",
    sendCode: async () => {},
  }),
);
if (toBeCreated.length === 0 && toBeAdded.length === 0) {
  console.log("better-auth's tables are up to date.");
} else {
  const sql = (await compileMigrations()).trim();
  const next = String(files.length + 1).padStart(4, "0");
  const path = join(migrationsDir, `${next}_auth.sql`);
  const header = "-- better-auth's tables, generated by scripts/auth-migration.ts. Don't edit.\n";
  await writeFile(path, `${header}${sql.replaceAll(/;\s*/g, ";\n")}\n`);
  console.log(`Wrote ${path}`);
}
